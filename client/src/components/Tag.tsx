/** Visual label that separates facts (what a document states) from AI interpretation. */
export function Tag({ kind }: { kind: 'fact' | 'ai' }) {
  return kind === 'ai' ? (
    <span className="tag tag-ai" title="Generated by the AI from the extracted facts">
      AI
    </span>
  ) : (
    <span className="tag tag-fact" title="Stated in the document">
      Fact
    </span>
  );
}
